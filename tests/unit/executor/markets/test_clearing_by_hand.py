"""Unit -- market clearing against hand-computed books. This is L3.

**Nothing in the suite had ever cleared a market.** Every `markets.yaml` a test ran set
`method: None`, so `__method_pda` -- the periodic double auction, and the method
`config_templates/markets.yaml` selects for a new user -- had never executed (#223). This file
drives the real `ElectricityMarket` over books written out by hand, and asserts the cleared
quantities, the clearing price and *who traded with whom* against numbers derived from the
algorithm on paper rather than from a recorded run.

**Why by hand and not by reference.** A reference generated by running the code pins today's
behaviour and cannot detect that today's behaviour is wrong. Every number asserted below was
computed by hand first -- the derivations are written out above the tests that use them -- and
the code was then found to agree. `tests/e2e/test_market_clearing.py` is the complement: it runs
the one shipped example that clears, which is what settles the questions no unit fixture can
(that the executor reaches this code at all, and which trading strategy it reaches it with).

**The books deliberately use equal quantities on both sides.** `__method_pda` joins the bid and
offer ladders on their *cumulative* energy (`energy_cumsum`), so a book whose two ladders share
their cumulative breakpoints produces one clean bid-versus-offer row per breakpoint, and the
result is the textbook double auction that can be checked on paper. Unequal quantities are
covered separately by `test_pda_partially_clears_the_larger_bid`, which is where the backward
fill -- the part of the algorithm that is *not* textbook -- becomes observable.

**Prices are in EURe-7/Wh**, the unit the retailer table and the whole executor use, and the two
retailer values here (500 / 1500) are the ones the shipped configs emit. Quantities are Wh.
"""
import datetime as dt

import polars as pl
import pytest

import hamlet.constants as c
from hamlet.executor.markets.electricity import ElectricityMarket
from hamlet.executor.utilities.database.market_db import MarketDB

TIMESTAMP = dt.datetime(2021, 3, 24, 0, 0, tzinfo=dt.timezone.utc)
TIMESTEP = dt.datetime(2021, 3, 24, 1, 0, tzinfo=dt.timezone.utc)
REGION, MARKET, NAME, ENERGY = 'r1', 'electricity', 'lem', 'electricity'

#: The retailer's two prices, in EURe-7/Wh, following the convention every shipped config uses:
#: `_out` is the direction the agent pays for. So the retailer *sells* at `RETAILER_SELLS` and
#: *buys* feed-in at `RETAILER_BUYS`. See `tests/unit/creator/markets/test_retailer_convention.py`.
RETAILER_BUYS = 500
RETAILER_SELLS = 1500

#: The retailer's agent id, as the Creator writes it and `__method_none` hard-codes it.
RETAILER_ID = 'retailer'

#: The columns the executor actually hands the market, taken from a real `scenario_with_market`
#: run rather than from `c.TS_BIDS_OFFERS`: the agents' table carries **eleven** columns, not the
#: schema's thirteen -- `price_in` and `price_out` are dropped by `_postprocess_bids_offers`
#: before the book ever reaches the market. `__create_bids_offers` does
#: `retailer.select(self.bids_offers.columns)`, so a fixture carrying the extra two would send the
#: retailer down a path no run takes. `test_the_book_matches_what_a_run_produces` keeps this
#: honest.
BOOK_COLUMNS = [c.TC_TIMESTAMP, c.TC_TIMESTEP, c.TC_REGION, c.TC_MARKET, c.TC_NAME,
                c.TC_TYPE_ENERGY, c.TC_ID_AGENT, c.TC_ENERGY_IN, c.TC_ENERGY_OUT,
                c.TC_PRICE_PU_IN, c.TC_PRICE_PU_OUT]


def book(rows):
    """A bids-and-offers table from `(agent, energy_in, energy_out, price_pu_in, price_pu_out)`.

    One row per agent, which is what the executor produces: `_preprocess_bids_offers` turns an
    agent's net position at a timestep into *either* an `energy_in` *or* an `energy_out`, never
    both. See `test_pda_does_not_exclude_self_trading` for what that rules out.
    """
    if not rows:
        return pl.DataFrame(schema={col: c.SCHEMA[col] for col in BOOK_COLUMNS})

    frame = pl.DataFrame(
        [{c.TC_TIMESTAMP: TIMESTAMP, c.TC_TIMESTEP: TIMESTEP, c.TC_REGION: REGION,
          c.TC_MARKET: MARKET, c.TC_NAME: NAME, c.TC_TYPE_ENERGY: ENERGY,
          c.TC_ID_AGENT: agent, c.TC_ENERGY_IN: energy_in, c.TC_ENERGY_OUT: energy_out,
          c.TC_PRICE_PU_IN: price_in, c.TC_PRICE_PU_OUT: price_out}
         for agent, energy_in, energy_out, price_in, price_out in rows])
    return frame.select(BOOK_COLUMNS).cast({col: c.SCHEMA[col] for col in BOOK_COLUMNS})


def retailer_table(energy_in=0, energy_out=0, buys=RETAILER_BUYS, sells=RETAILER_SELLS):
    """The retailer's row for `TIMESTEP`, in the shape the Creator writes it.

    The column names are the Creator's own (`<commodity>_<key>_<direction>`); the market strips
    the leading `energy_` and renames the price pair, which is why `energy_price_in` becomes the
    price the retailer *buys* at. Defaults to **zero quantity on both sides**, which drops the
    retailer out of the book entirely at `__split_bids_offers` (it filters on `> 0`) and leaves a
    pure agent-to-agent market. Tests that want the retailer to trade pass a quantity.
    """
    frame = pl.DataFrame([{
        c.TC_TIMESTAMP: TIMESTEP, c.TC_REGION: REGION, c.TC_MARKET: MARKET, c.TC_NAME: NAME,
        c.TC_ID_AGENT: 'retailer', c.TC_TYPE_ENERGY: ENERGY,
        f'{c.TT_ENERGY}_{c.TC_PRICE}_{c.PF_IN}': buys,
        f'{c.TT_ENERGY}_{c.TC_PRICE}_{c.PF_OUT}': sells,
        f'{c.TT_ENERGY}_{c.TC_ENERGY}_{c.PF_IN}': energy_in,
        f'{c.TT_ENERGY}_{c.TC_ENERGY}_{c.PF_OUT}': energy_out,
        f'{c.TT_ENERGY}_{c.TC_QUALITY}': 0,
        f'{c.TT_GRID}_{c.TT_MARKET}_{c.PF_IN}': 0, f'{c.TT_GRID}_{c.TT_MARKET}_{c.PF_OUT}': 400,
        f'{c.TT_GRID}_{c.TT_RETAIL}_{c.PF_IN}': 0, f'{c.TT_GRID}_{c.TT_RETAIL}_{c.PF_OUT}': 800,
        f'{c.TT_LEVIES}_{c.TC_PRICE}_{c.PF_IN}': 0,
        f'{c.TT_LEVIES}_{c.TC_PRICE}_{c.PF_OUT}': 1800,
        f'{c.TT_BALANCING}_{c.TC_PRICE}_{c.PF_IN}': 400,
        f'{c.TT_BALANCING}_{c.TC_PRICE}_{c.PF_OUT}': 1600,
        f'{c.TT_BALANCING}_{c.TC_ENERGY}_{c.PF_IN}': 1_000_000,
        f'{c.TT_BALANCING}_{c.TC_ENERGY}_{c.PF_OUT}': 1_000_000,
    }])
    return frame.cast({c.TC_TIMESTAMP: c.SCHEMA[c.TC_TIMESTAMP], c.TC_REGION: pl.Categorical,
                       c.TC_MARKET: pl.Categorical, c.TC_NAME: pl.Categorical,
                       c.TC_TYPE_ENERGY: pl.Categorical})


class OneMarketDatabase:
    """The single call `ElectricityMarket.__init__` makes on the `Database`.

    A stub rather than a real `Database`, which would need a whole scenario on disk. The market's
    own `__init__` runs unmodified against it, so the method and pricing registries under test are
    the real ones -- a mutation to `self.methods` is visible here.
    """

    def __init__(self, bids_offers):
        self.bids_offers = bids_offers
        self.calls = []

    def get_bids_offers(self, region, market_type, market_name, timestep):
        self.calls.append((region, market_type, market_name, timestep))
        return self.bids_offers


def make_market(rows, retailer=None, method=c.MCM_PDA, pricing=c.MP_UNIFORM,
                actions=c.MA_CLEAR):
    """A real `ElectricityMarket` over a hand-written book, ready for `execute()`."""
    database = object.__new__(MarketDB)
    database.market_type, database.market_name = MARKET, NAME
    database.market_transactions = pl.DataFrame(schema=c.TS_MARKET_TRANSACTIONS)
    database.bids_cleared = pl.DataFrame(schema=c.TS_BIDS_CLEARED)
    database.bids_uncleared = pl.DataFrame(schema=c.TS_BIDS_UNCLEARED)
    database.offers_cleared = pl.DataFrame(schema=c.TS_OFFERS_CLEARED)
    database.offers_uncleared = pl.DataFrame(schema=c.TS_OFFERS_UNCLEARED)
    database.retailer = retailer_table() if retailer is None else retailer

    tasks = {c.TC_TIMESTAMP: TIMESTAMP, c.TC_TIMESTEP: TIMESTEP, c.TC_REGION: REGION,
             c.TC_MARKET: MARKET, c.TC_NAME: NAME, c.TC_TYPE_ENERGY: ENERGY,
             c.TC_ACTIONS: actions, c.TC_CLEARING_TYPE: c.MCT_EX_ANTE,
             c.TC_CLEARING_METHOD: method, c.TC_CLEARING_PRICING: pricing,
             c.TC_COUPLING: None}

    return ElectricityMarket(market=database, tasks=tasks,
                             database=OneMarketDatabase(book(rows)))


def cleared(market):
    """`{agent: (energy, price_pu, price)}` for the two cleared tables, ids as plain strings.

    Categoricals are cast to `Utf8` before anything compares them: polars compares two
    Categorical columns by their *encoding* unless they share a string cache, and a comparison
    that silently answers about encodings once invented 369 file differences in this repository.
    """
    bids = {row[c.TC_ID_AGENT_IN]: (row[c.TC_ENERGY_IN], row[c.TC_PRICE_PU_IN], row[c.TC_PRICE_IN])
            for row in market.bids_cleared
            .with_columns(pl.col(c.TC_ID_AGENT_IN).cast(pl.Utf8)).to_dicts()}
    offers = {row[c.TC_ID_AGENT_OUT]: (row[c.TC_ENERGY_OUT], row[c.TC_PRICE_PU_OUT],
                                       row[c.TC_PRICE_OUT])
              for row in market.offers_cleared
              .with_columns(pl.col(c.TC_ID_AGENT_OUT).cast(pl.Utf8)).to_dicts()}
    return bids, offers


def uncleared(market):
    """`{agent: energy}` for the two uncleared tables, ids as plain strings."""
    bids = {row[c.TC_ID_AGENT_IN]: row[c.TC_ENERGY_IN]
            for row in market.bids_uncleared
            .with_columns(pl.col(c.TC_ID_AGENT_IN).cast(pl.Utf8)).to_dicts()}
    offers = {row[c.TC_ID_AGENT_OUT]: row[c.TC_ENERGY_OUT]
              for row in market.offers_uncleared
              .with_columns(pl.col(c.TC_ID_AGENT_OUT).cast(pl.Utf8)).to_dicts()}
    return bids, offers


def transactions(market):
    """The transactions table as `(kind, agent, energy_in, energy_out, price_pu_in, price_pu_out)`."""
    frame = market.transactions.with_columns(
        pl.col(c.TC_TYPE_TRANSACTION).cast(pl.Utf8), pl.col(c.TC_ID_AGENT).cast(pl.Utf8))
    return [(row[c.TC_TYPE_TRANSACTION], row[c.TC_ID_AGENT], row[c.TC_ENERGY_IN],
             row[c.TC_ENERGY_OUT], row[c.TC_PRICE_PU_IN], row[c.TC_PRICE_PU_OUT])
            for row in frame.to_dicts()]


# ----------------------------------------------------------------------------------------------
# The book every price-and-quantity assertion below is derived from.
#
# Six agents, 1000 Wh each, so the two cumulative ladders share their breakpoints at 1000, 2000
# and 3000 Wh and the join produces exactly three bid-versus-offer rows:
#
#     cumsum   bid                  offer                 in >= out ?
#      1000    buyer_a  @ 3000      seller_x  @ 1200      3000 >= 1200   cleared
#      2000    buyer_b  @ 2000      seller_y  @ 1800      2000 >= 1800   cleared
#      3000    buyer_c  @ 1000      seller_z  @ 2500      1000 <  2500   not cleared
#
# So 2000 Wh trades. The marginal pair is (buyer_b, seller_y) and uniform pricing takes its
# midpoint: (2000 + 1800) / 2 = 1900. Every cleared position is priced at 1900, and each carries
# min(energy_in, energy_out) = 1000 Wh, so each is worth 1900 * 1000 = 1_900_000.
#
# The six prices are chosen so that no two are equal and so that 1900 is none of them: an
# implementation that echoed a *submitted* price back instead of computing a clearing price fails
# rather than coinciding. `test_the_textbook_book_brackets_the_clearing_price` asserts that.
# ----------------------------------------------------------------------------------------------
TEXTBOOK = [
    ('buyer_a', 1000, 0, 3000, 0),
    ('buyer_b', 1000, 0, 2000, 0),
    ('buyer_c', 1000, 0, 1000, 0),
    ('seller_x', 0, 1000, 0, 1200),
    ('seller_y', 0, 1000, 0, 1800),
    ('seller_z', 0, 1000, 0, 2500),
]

#: The clearing price of `TEXTBOOK`, computed by hand above. **An absolute value, never derived
#: from the book at runtime**, so a change to the pricing rule cannot move the expectation with
#: it.
TEXTBOOK_PRICE = 1900
TEXTBOOK_QUANTITY = 1000


def test_the_book_matches_what_a_run_produces():
    """The fixture's columns and dtypes are the ones the executor really hands the market.

    A hand-written book that has drifted from the real one is a harness testing a shape nothing
    produces -- and it would drift silently, because every assertion below would keep passing.
    The reference is `c.TS_BIDS_OFFERS` minus the two price columns `_postprocess_bids_offers`
    drops, which is what a `scenario_with_market` run was observed to carry.
    """
    produced = book(TEXTBOOK)

    assert dict(produced.schema) == {col: c.SCHEMA[col] for col in BOOK_COLUMNS}
    assert set(BOOK_COLUMNS) == set(c.TS_BIDS_OFFERS) - {c.TC_PRICE_IN, c.TC_PRICE_OUT}
    assert len(produced) == len(TEXTBOOK)


def test_the_textbook_book_brackets_the_clearing_price():
    """The harness asserts its own premise: 1900 is a *result*, not one of the inputs.

    If the clearing price coincided with a submitted price, every assertion on it would also pass
    for an implementation that echoed a bid back. Deriving a test input from the value under test
    is what makes that value unfalsifiable.
    """
    submitted = ({price for _, _, _, price, _ in TEXTBOOK}
                 | {price for _, _, _, _, price in TEXTBOOK}) - {0}

    assert TEXTBOOK_PRICE not in submitted
    assert min(submitted) < TEXTBOOK_PRICE < max(submitted)
    assert len(submitted) == len(TEXTBOOK), 'two agents share a price, so ties decide the result'


def test_pda_clears_the_textbook_double_auction():
    """Who traded, how much, and at what price -- all of it per agent, by name.

    Asserting the totals alone would pass with the same energy handed to the wrong agents, which
    is exactly the failure a sum cannot see.
    """
    market = make_market(TEXTBOOK)
    market.execute()

    bids, offers = cleared(market)

    assert bids == {'buyer_a': (TEXTBOOK_QUANTITY, TEXTBOOK_PRICE, 1_900_000),
                    'buyer_b': (TEXTBOOK_QUANTITY, TEXTBOOK_PRICE, 1_900_000)}
    assert offers == {'seller_x': (TEXTBOOK_QUANTITY, TEXTBOOK_PRICE, 1_900_000),
                      'seller_y': (TEXTBOOK_QUANTITY, TEXTBOOK_PRICE, 1_900_000)}


# ----------------------------------------------------------------------------------------------
# The clearing comparison is `>=`, and this is the book that says so.
#
#     cumsum   bid                 offer               in >= out ?    in > out ?
#      1000    buyer_a @ 3000      seller_x @ 1200     cleared        cleared
#      2000    buyer_b @ 1500      seller_y @ 1500     cleared        NOT cleared
#
# A bid that exactly meets an offer trades. `TEXTBOOK` cannot show this -- none of its six prices
# coincides, by design, so `>=` and `>` agree on it and either spelling passes. The two spellings
# disagree here on *both* the quantity (2000 Wh against 1000) and the price (1500 against 2100),
# because dropping the marginal pair also moves which pair is marginal.
# ----------------------------------------------------------------------------------------------
MEETS_EXACTLY = [
    ('buyer_a', 1000, 0, 3000, 0),
    ('buyer_b', 1000, 0, 1500, 0),
    ('seller_x', 0, 1000, 0, 1200),
    ('seller_y', 0, 1000, 0, 1500),
]


def test_pda_clears_a_bid_that_exactly_meets_an_offer():
    """`>=`, not `>`. The whole marginal pair trades, and it sets the price.

    Both halves are asserted: with `>` the pair would drop out, leaving 1000 Wh cleared at 2100
    instead of 2000 Wh at 1500. Either number alone would catch it; both are here because they
    fail for the same reason and reading them together is what says why.
    """
    market = make_market(MEETS_EXACTLY)
    market.execute()

    bids, offers = cleared(market)

    assert bids == {'buyer_a': (1000, 1500, 1_500_000),
                    'buyer_b': (1000, 1500, 1_500_000)}
    assert offers == {'seller_x': (1000, 1500, 1_500_000),
                      'seller_y': (1000, 1500, 1_500_000)}
    assert market.bids_cleared[c.TC_ENERGY_IN].sum() == 2000
    assert uncleared(market) == ({}, {})


def test_the_meeting_book_really_does_have_a_pair_at_the_same_price():
    """The premise of the test above, asserted rather than assumed.

    Change `buyer_b`'s price by one unit and `test_pda_clears_a_bid_that_exactly_meets_an_offer`
    stops testing the boundary while still passing -- so the equality is checked here, where
    breaking it is a failure rather than a silent loss of coverage.
    """
    bids = {agent: price for agent, energy_in, _, price, _ in MEETS_EXACTLY if energy_in}
    offers = {agent: price for agent, _, energy_out, _, price in MEETS_EXACTLY if energy_out}

    assert min(bids.values()) == min(price for price in offers.values() if price == 1500)
    assert sorted(bids.values())[0] in offers.values()


def test_pda_leaves_the_out_of_the_money_positions_uncleared():
    """`buyer_c` bid below every remaining offer and `seller_z` asked above every remaining bid."""
    market = make_market(TEXTBOOK)
    market.execute()

    bids, offers = uncleared(market)

    assert bids == {'buyer_c': TEXTBOOK_QUANTITY}
    assert offers == {'seller_z': TEXTBOOK_QUANTITY}


def test_pda_prices_everyone_at_the_marginal_midpoint():
    """Uniform pricing: one price for the whole clearing, and it is 1900.

    Checked as a set so that a rule pricing *some* trade differently -- discriminatory pricing
    leaking into the uniform branch -- fails rather than being averaged away.
    """
    market = make_market(TEXTBOOK)
    market.execute()

    prices = (set(market.bids_cleared[c.TC_PRICE_PU_IN].to_list())
              | set(market.offers_cleared[c.TC_PRICE_PU_OUT].to_list()))

    assert prices == {TEXTBOOK_PRICE}


def test_pda_writes_one_transaction_per_side_and_types_them_as_market_trades():
    """No retailer took part, so all four transaction rows are `market` rather than `retail`."""
    market = make_market(TEXTBOOK)
    market.execute()

    assert sorted(transactions(market)) == sorted([
        (c.TT_MARKET, 'buyer_a', TEXTBOOK_QUANTITY, None, TEXTBOOK_PRICE, None),
        (c.TT_MARKET, 'buyer_b', TEXTBOOK_QUANTITY, None, TEXTBOOK_PRICE, None),
        (c.TT_MARKET, 'seller_x', None, TEXTBOOK_QUANTITY, None, TEXTBOOK_PRICE),
        (c.TT_MARKET, 'seller_y', None, TEXTBOOK_QUANTITY, None, TEXTBOOK_PRICE),
    ])


# ----------------------------------------------------------------------------------------------
# The retailer takes part.
#
#     bids   sorted by price descending       offers sorted by price ascending
#      buyer_a  3000    cumsum     1_000       seller_x   1200   cumsum     1_000
#      buyer_b  2000    cumsum     2_000       retailer   1500   cumsum   101_000
#      buyer_c  1000    cumsum     3_000       seller_y   1800   cumsum   102_000
#      retailer  500    cumsum   103_000       seller_z   2500   cumsum   103_000
#
# The outer join on `energy_cumsum` gives six rows; the backward fill carries the *next* ladder
# entry upwards into the gaps, so rows 2000 and 3000 face the retailer's offer at 1500:
#
#     cumsum   bid            offer          in >= out ?
#       1_000  buyer_a 3000   seller_x 1200  cleared
#       2_000  buyer_b 2000   retailer 1500  cleared        <- the marginal pair
#       3_000  buyer_c 1000   retailer 1500  not cleared
#     101_000  retailer 500   retailer 1500  not cleared
#     102_000  retailer 500   seller_y 1800  not cleared
#     103_000  retailer 500   seller_z 2500  not cleared
#
# Uniform price = (2000 + 1500) / 2 = 1750. buyer_a takes 1000 Wh from seller_x; buyer_b takes
# min(1000, 100_000) = 1000 Wh from the retailer. `seller_y` is left uncleared *despite asking
# less than buyer_b bid* -- the retailer's 100 kWh offer sits ahead of it on the ladder. That is
# the merit order doing its job, and it is why this case is worth its own test.
# ----------------------------------------------------------------------------------------------
RETAILER_QUANTITY = 100_000
RETAILER_PRICE = 1750


def with_retailer():
    return make_market(TEXTBOOK, retailer=retailer_table(energy_in=RETAILER_QUANTITY,
                                                         energy_out=RETAILER_QUANTITY))


def test_the_retailer_clears_at_the_back_of_the_merit_order():
    market = with_retailer()
    market.execute()

    bids, offers = cleared(market)

    assert bids == {'buyer_a': (1000, RETAILER_PRICE, 1_750_000),
                    'buyer_b': (1000, RETAILER_PRICE, 1_750_000)}
    assert offers == {'seller_x': (1000, RETAILER_PRICE, 1_750_000),
                      'retailer': (1000, RETAILER_PRICE, 1_750_000)}


def test_a_cheaper_offer_behind_the_retailer_stays_uncleared():
    """`seller_y` asks 1800, below `buyer_b`'s 2000, and still does not trade.

    Not an anomaly: `buyer_b`'s 1000 Wh is exhausted against the retailer's offer, which sits
    ahead of `seller_y` on the ladder. Asserted so that a change which started clearing it is
    noticed as a change to the merit order rather than absorbed into a total.
    """
    market = with_retailer()
    market.execute()

    bids, offers = uncleared(market)

    assert bids == {'buyer_c': 1000}
    assert offers == {'seller_y': 1000, 'seller_z': 1000}


def test_a_trade_with_the_retailer_is_typed_retail_and_one_without_it_is_not():
    """Both types in one clearing, so neither can pass by being the only one present."""
    market = with_retailer()
    market.execute()

    by_agent = {agent: kind for kind, agent, *_ in transactions(market)}

    assert by_agent == {'buyer_a': c.TT_MARKET, 'seller_x': c.TT_MARKET,
                        'buyer_b': c.TT_RETAIL, 'retailer': c.TT_RETAIL}


# ----------------------------------------------------------------------------------------------
# `method: None`, the setting every runnable scenario ships.
#
# One agent buying 1000 Wh at the retailer's selling price and one selling 600 Wh at its buying
# price. `__method_none` routes both through the retailer and prices them at the retailer's own
# two prices, so the buyer pays 1500 * 1000 and the seller receives 500 * 600.
# ----------------------------------------------------------------------------------------------
RETAIL_ONLY = [('buyer_a', 1000, 0, RETAILER_SELLS, 0),
               ('seller_x', 0, 600, 0, RETAILER_BUYS)]


def retail_market(rows):
    return make_market(rows, method=c.MCM_NONE,
                       retailer=retailer_table(energy_in=RETAILER_QUANTITY,
                                               energy_out=RETAILER_QUANTITY))


def test_method_none_routes_both_sides_through_the_retailer():
    market = retail_market(RETAIL_ONLY)
    market.execute()

    bids, offers = cleared(market)

    # The agent buys 1000 Wh at the retailer's selling price; the retailer is the counterparty on
    # the offer side for the same quantity.
    assert bids['buyer_a'] == (1000, RETAILER_SELLS, RETAILER_SELLS * 1000)
    assert offers['retailer'] == (1000, RETAILER_SELLS, RETAILER_SELLS * 1000)
    # The agent sells 600 Wh at the retailer's buying price, and the retailer is the bidder.
    assert offers['seller_x'] == (600, RETAILER_BUYS, RETAILER_BUYS * 600)
    assert bids['retailer'] == (600, RETAILER_BUYS, RETAILER_BUYS * 600)

    assert set(bids) == {'buyer_a', 'retailer'}
    assert set(offers) == {'retailer', 'seller_x'}
    assert {kind for kind, *_ in transactions(market)} == {c.TT_RETAIL}


def test_method_none_leaves_nothing_uncleared_when_the_retailer_is_unconstrained():
    market = retail_market(RETAIL_ONLY)
    market.execute()

    assert uncleared(market) == ({}, {})


def test_method_none_refuses_a_bid_below_the_retailers_selling_price():
    """An agent unwilling to pay the retail price does not trade, and keeps its position.

    The bid is one unit below the ask rather than far below it, so the test brackets the
    comparison instead of merely being on the right side of it.
    """
    market = retail_market([('buyer_a', 1000, 0, RETAILER_SELLS - 1, 0)])
    market.execute()

    bids, offers = cleared(market)
    unbid, _ = uncleared(market)

    assert bids == {} and offers == {}
    assert unbid == {'buyer_a': 1000}


def test_method_none_accepts_a_bid_exactly_at_the_retailers_selling_price():
    """The other side of the same boundary: `>=`, not `>`.

    Paired with the test above so the comparison is bracketed from both directions; either test
    alone leaves one of the two spellings green.
    """
    market = retail_market([('buyer_a', 1000, 0, RETAILER_SELLS, 0)])
    market.execute()

    bids, _ = cleared(market)

    assert bids['buyer_a'] == (1000, RETAILER_SELLS, RETAILER_SELLS * 1000)


