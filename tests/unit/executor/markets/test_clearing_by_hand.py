def test_pda_partially_clears_the_larger_bid():
    """A 1500 Wh bid against a 1000 Wh offer trades 1000 and leaves 500 outstanding.

    The two ladders do not share a breakpoint here, so this is the case that exercises the
    backward fill: the join produces a row at 1000 (the offer's cumsum) into which the bid at
    1500 is filled, and a row at 1500 whose offer side stays null and drops out of the
    comparison. Cleared energy is min(1500, 1000) = 1000 and the price is the midpoint of the one
    surviving pair, (3000 + 1200) / 2 = 2100.
    """
    market = make_market([('buyer_a', 1500, 0, 3000, 0), ('seller_x', 0, 1000, 0, 1200)])
    market.execute()

    bids, offers = cleared(market)
    unbid, unoffered = uncleared(market)

    assert bids == {'buyer_a': (1000, 2100, 2_100_000)}
    assert offers == {'seller_x': (1000, 2100, 2_100_000)}
    assert unbid == {'buyer_a': 500}
    assert unoffered == {}


def test_pda_does_not_exclude_self_trading():
    """**A stated gap, not an endorsement.** `__method_pda` has no self-trade filter.

    `__method_none` filters `id_agent_in != id_agent_out` explicitly; `__method_pda` does not, so
    an agent submitting on both sides of one clearing sells to itself at 2100. It is unreachable
    through the shipped trading strategies -- `_preprocess_bids_offers` nets an agent's position
    into one direction per timestep, which
    `test_no_cleared_position_is_an_agent_trading_with_itself` asserts of every book here -- so
    this is latent rather than live. Pinned so the asymmetry between the two methods is a
    recorded fact rather than a surprise. #223.
    """
    market = make_market([('both', 1000, 1000, 3000, 1200)])
    market.execute()

    bids, offers = cleared(market)

    assert bids == {'both': (1000, 2100, 2_100_000)}
    assert offers == {'both': (1000, 2100, 2_100_000)}


def test_method_none_routes_a_two_sided_agent_through_the_retailer_on_both_sides():
    """The same two-sided agent buys from and sells to the retailer, never to itself.

    **What `__method_none`'s `id_agent_in != id_agent_out` filter actually removes is not this.**
    By the time it runs, every missing counterparty has been filled in with `'retailer'`, so an
    agent can never appear on both ends of one row -- its bid row faces the retailer and its offer
    row faces the retailer. What the filter removes is the *retailer against itself*, which
    `test_method_none_drops_the_retailers_trade_with_itself` covers. Deleting the filter leaves
    this test green, measured; the name it used to carry claimed otherwise.
    """
    market = retail_market([('both', 1000, 1000, RETAILER_SELLS, RETAILER_BUYS)])
    market.execute()

    bids, offers = cleared(market)

    assert bids == {'both': (1000, RETAILER_SELLS, RETAILER_SELLS * 1000),
                    'retailer': (1000, RETAILER_BUYS, RETAILER_BUYS * 1000)}
    assert offers == {'both': (1000, RETAILER_BUYS, RETAILER_BUYS * 1000),
                      'retailer': (1000, RETAILER_SELLS, RETAILER_SELLS * 1000)}


#: A retailer whose buying and selling prices are equal. **Deliberately degenerate**, and it
#: breaks the no-arbitrage property `tests/unit/creator/markets/test_retailer_convention.py`
#: requires of every shipped config -- that is the point. With a normal spread the retailer's own
#: bid (at `RETAILER_BUYS`) can never meet its own offer (at `RETAILER_SELLS`), so the
#: retailer-versus-retailer rows never clear and the self-trade filter has nothing to do. At a
#: zero spread they do meet, which is the only way to observe the filter at all.
FLAT_RETAILER_PRICE = 900


def test_method_none_drops_the_retailers_trade_with_itself():
    """The self-trade filter, made observable.

    Measured with the filter removed on the bid side: the retailer acquires two extra
    transactions of **100_000 Wh** -- its whole capacity, bought from and sold to itself -- on top
    of the four real ones. Nothing else in this file notices, because with a normal price spread
    those rows cannot clear.
    """
    market = make_market(
        [('both', 1000, 1000, FLAT_RETAILER_PRICE, FLAT_RETAILER_PRICE)], method=c.MCM_NONE,
        retailer=retailer_table(energy_in=RETAILER_QUANTITY, energy_out=RETAILER_QUANTITY,
                                buys=FLAT_RETAILER_PRICE, sells=FLAT_RETAILER_PRICE))
    market.execute()

    assert sorted(transactions(market), key=repr) == sorted([
        (c.TT_RETAIL, 'both', 1000, None, FLAT_RETAILER_PRICE, None),
        (c.TT_RETAIL, 'both', None, 1000, None, FLAT_RETAILER_PRICE),
        (c.TT_RETAIL, RETAILER_ID, 1000, None, FLAT_RETAILER_PRICE, None),
        (c.TT_RETAIL, RETAILER_ID, None, 1000, None, FLAT_RETAILER_PRICE),
    ], key=repr)

    energies = {energy for _, _, energy_in, energy_out, _, _ in transactions(market)
                for energy in (energy_in, energy_out) if energy is not None}
    assert RETAILER_QUANTITY not in energies, (
        'the retailer traded its whole capacity with itself')


