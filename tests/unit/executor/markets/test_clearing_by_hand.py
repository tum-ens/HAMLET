def test_the_cleared_energy_balances(run_book):
    """Sum of cleared energy in equals sum of cleared energy out. Nothing created, nothing lost.

    The expected total is pinned as well as the equality: `0 == 0` satisfies a conservation law
    and says nothing, and a book that stopped clearing would otherwise pass this silently.
    """
    name, _, market = run_book

    bought = market.bids_cleared[c.TC_ENERGY_IN].sum()
    sold = market.offers_cleared[c.TC_ENERGY_OUT].sum()

    assert bought == sold
    assert bought == CLEARED_TOTALS[name]


def test_uncleared_is_submitted_minus_cleared(run_book):
    """Per agent, per side: what was submitted, less what cleared, is what is left uncleared.

    Per agent rather than in total, because a total is blind to energy attributed to the wrong
    agent. The retailer is excluded because `__create_market_tables` deliberately drops it from
    the uncleared tables -- its quantity is a capacity, not an unmet position.
    """
    _, rows, market = run_book

    submitted_in = {agent: energy_in for agent, energy_in, _, _, _ in rows if energy_in}
    submitted_out = {agent: energy_out for agent, _, energy_out, _, _ in rows if energy_out}
    took, gave = cleared_energy(market)
    unbid, unoffered = uncleared(market)

    for agent, submitted in submitted_in.items():
        assert unbid.get(agent, 0) == submitted - took.get(agent, 0), f'bid side of {agent}'
    for agent, submitted in submitted_out.items():
        assert unoffered.get(agent, 0) == submitted - gave.get(agent, 0), f'offer side of {agent}'

    assert set(unbid) <= set(submitted_in), 'an agent that submitted no bid has an uncleared one'
    assert set(unoffered) <= set(submitted_out)


def test_no_cleared_position_is_an_agent_trading_with_itself(run_book):
    """No agent appears on both sides of the same clearing.

    Holds for every book here **because of how bids are built, not because the market checks**:
    `_preprocess_bids_offers` gives an agent either an `energy_in` or an `energy_out` at a given
    timestep, never both. `__method_pda` has no self-trade filter --
    `test_pda_does_not_exclude_self_trading` pins that separately -- so this test would go green
    for the wrong reason if a book ever carried a two-sided agent. The first assertion is what
    stops that.

    The retailer is exempt: it is on both sides of every `method: None` clearing by construction,
    buying feed-in from one agent while selling to another, and those are two different trades.
    """
    _, rows, market = run_book

    two_sided = [agent for agent, energy_in, energy_out, _, _ in rows if energy_in and energy_out]
    assert not two_sided, (
        f'{two_sided} submit on both sides, so this invariant would be testing the market rather '
        f'than the book; see test_pda_does_not_exclude_self_trading')

    took, gave = cleared_energy(market)
    both_sides = (set(took) & set(gave)) - {RETAILER_ID}

    assert not both_sides


